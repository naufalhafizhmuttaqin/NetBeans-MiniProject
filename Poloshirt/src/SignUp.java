    private void CreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CreateActionPerformed
        int value;
        String pass  = String.valueOf(Password.getPassword());
        
        
        if(Fname.getText().trim().isEmpty() && Lname.getText().trim().isEmpty() && pass.trim().isEmpty()){
            Warning.setText("Kolom Tidak Boleh Kosong!");
            value = -1;
        }
        
        else if(Fname.getText().trim().isEmpty()){
            Warning.setText("Fname Tidak Boleh Kosong!");
            value = -1;
        }
        
        else if(Lname.getText().trim().isEmpty()){
            Warning.setText("Last Name Tidak Boleh Kosong!");
            value = -1;
        }
        
        else if(pass.trim().isEmpty()){
            Warning.setText("Password Tidak Boleh Kosong!");
            value = -1;
        }
        
         else if(NoHp.getText().trim().isEmpty()){
            Warning.setText("No Hp Tidak Boleh Kosong!");
            value = -1;
        }
         
          else if(Address.getText().trim().isEmpty()){
            Warning.setText("Alamat Tidak Boleh Kosong!");
            value = -1;
        }
          else if(Email.getText().trim().isEmpty()){
            Warning.setText("Email Tidak Boleh Kosong!");
            value = -1;
          }
        
        else {
            value = 1;

        }

       
        String db = "insert into Akun values (?,?,?,?,?,?)";
        try{
            if (value>0){
          
             PreparedStatement statement = cons.prepareStatement(db);
             statement.setString(1,Email.getText());
             statement.setString(2,Fname.getText());
             statement.setString(3,Lname.getText());
             statement.setString(4,String.valueOf(Password.getPassword()));
             statement.setString(5,Address.getText());
             statement.setString(6,NoHp.getText());
          
              statement.executeUpdate();
              JOptionPane.showMessageDialog(null,"Sign Up Complete! You Will Be Directed Back To The Login Form!");
              Login Login = new Login();
              Login.setVisible(true);
               this.dispose();
            }

        }
           catch (Exception E){
           JOptionPane.showMessageDialog(null, E);
           }
      
      
    }//GEN-LAST:event_CreateActionPerformed

