package pkg8_operatorpembanding;

public class Main {

    public static void main(String[] args) {
        /*
            ==
            !=
            >
            >=
            <
            <=
        */
        
        int a = 10;
        int b = 6;
        
        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a > b);
        System.out.println(a >= b);
        System.out.println(a < b);
        System.out.println(a <= b);
    }
    
}
